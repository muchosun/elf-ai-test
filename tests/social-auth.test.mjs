import assert from 'node:assert/strict';
import {authResponse, authConfig, providerStatus} from '../lib/social-auth.js';
import {encode} from '@auth/core/jwt';
import {loadSocialSession, socialSignIn} from '../social-auth-client.js';

const origin='https://elf.pink';
const env={AUTH_URL:origin,AUTH_SECRET:'synthetic-test-secret-with-sufficient-entropy',AUTH_GOOGLE_ID:'synthetic-id',AUTH_GOOGLE_SECRET:'synthetic-secret'};
const request=(path,options)=>new Request(origin+'/api/auth/'+path,options);
assert.deepEqual(providerStatus({}).map(p=>p.enabled),[false,false,false,false]);
let response=await authResponse(request('status'),{});
assert.equal(response.headers.get('cache-control'),'no-store');
assert.equal((await response.json()).providers.length,4);
response=await authResponse(request('signin/google',{method:'POST'}),{});
assert.equal(response.status,503);
assert.equal(await loadSocialSession(async()=>Response.json(null)),null);
await assert.rejects(socialSignIn('Google',async()=>Response.json({providers:providerStatus({})})),/provider_not_configured/);
response=await authResponse(new Request('https://evil.example/api/auth/session'),env);
assert.equal(response.status,403);
response=await authResponse(request('session'),env);
assert.equal(await response.json(),null);
response=await authResponse(request('providers'),env);
const providers=await response.json();
assert.deepEqual(Object.keys(providers),['google']);
assert.equal(providers.google.callbackUrl,origin+'/api/auth/callback/google');
assert.ok(!JSON.stringify(providers).includes('synthetic-secret'));
// A login or logout without a CSRF token cannot mutate a session.
response=await authResponse(request('signout',{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded','X-Auth-Return-Redirect':'1'},body:'callbackUrl=https%3A%2F%2Fevil.example'}),env);
assert.match(await response.text(),/MissingCSRF/);
const config=authConfig(env);
let token=await config.callbacks.jwt({token:{name:'Synthetic'},account:{provider:'google',providerAccountId:'test-subject'}});
assert.match(token.elfId,/^[\da-f]{8}-[\da-f]{4}-5[\da-f]{3}-a[\da-f]{3}-[\da-f]{12}$/);
const token2=await config.callbacks.jwt({token:{},account:{provider:'facebook',providerAccountId:'test-subject'}});
assert.notEqual(token.elfId,token2.elfId);
const cookie='__Secure-authjs.session-token';
const jwt=await encode({token,secret:env.AUTH_SECRET,salt:cookie});
response=await authResponse(request('session',{headers:{cookie:`${cookie}=${jwt}`}}),env);
const session=await response.json();
assert.equal(session.user.id,token.elfId);
assert.ok(!('access_token' in session.user));
assert.match(response.headers.get('set-cookie'),/HttpOnly/);
assert.match(response.headers.get('set-cookie'),/Secure/);
assert.equal(await config.callbacks.redirect({url:'https://evil.example/',baseUrl:origin}),origin+'/index.html#signup');
console.log('PASS: disabled providers, no-secret behavior, canonical host, real encrypted session, secure cookies, stable identity, CSRF, redirect confinement');
