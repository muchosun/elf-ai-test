import assert from 'node:assert/strict';
import {beginGoogleRegistration,completeGoogleRegistration} from '../google-registration.js';
const store=()=>{const m=new Map();return {getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,v),removeItem:k=>m.delete(k)}};
const pending=store(), remembered=store(),calls=[],pixel={registration:m=>calls.push(m)},user={id:'synthetic-account'};
assert.equal(completeGoogleRegistration(user,pixel,pending,remembered,100),false);
beginGoogleRegistration(pending,100);
assert.equal(completeGoogleRegistration(null,pixel,pending,remembered,101),false);
assert.equal(completeGoogleRegistration(user,pixel,pending,remembered,102),true);
assert.deepEqual(calls,['google']);
assert.equal(completeGoogleRegistration(user,pixel,pending,remembered,103),false);
beginGoogleRegistration(pending,104);
assert.equal(completeGoogleRegistration(user,pixel,pending,remembered,105),false);
assert.equal(calls.length,1);
beginGoogleRegistration(pending,100);
assert.equal(completeGoogleRegistration({id:'other'},pixel,pending,remembered,1000000),false);
beginGoogleRegistration(pending,100);
assert.equal(completeGoogleRegistration({id:'other'},null,pending,remembered,101),false);
const blocked={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
assert.doesNotThrow(()=>beginGoogleRegistration(blocked));
assert.equal(completeGoogleRegistration(user,pixel,blocked,remembered),false);
console.log('PASS: Google verified session required, signup intent, once per browser/account, no replay, expiry and blocked analytics/storage safe');
